// Фикстура композера: режим команды чату и список, который до него доводит.
//
// Снимать это в приложении неудобно: состояние зависит от набранного текста, и
// на стенде оно задаётся черновиком (`initialText`) сразу. Кейса два — с
// командой и с обычным вопросом: смысл правила «уйдёт чату, а не модели» весь в
// разнице между ними.
//
// Подсветка самого `/compact` — CSS Custom Highlight API, и она на снимке видна
// только в браузере с его поддержкой (Chromium стенда — с ним).

const noop = () => {};

const model = {
  config: { defaultModel: { id: 'gpt' } },
  options: [{ id: 'gpt', label: 'GPT' }],
  selected: 'gpt',
  onChange: noop,
};

const mode = { options: [{ id: 'review', label: 'Ревью' }], selected: '', onChange: noop };

const project = {
  options: [{ id: 'kb', label: 'Project' }],
  defaultId: 'kb',
  selected: 'kb',
  onChange: noop,
};

const base = { model, mode, project, chatId: 'chat-1' };

/** Набрана команда: строка над полем и подсвеченный триггер. */
export const command = { ...base, initialText: '/compact подробнее про миграции' };

/** Обычный вопрос со слэшем внутри: ни строки, ни подсветки — команды здесь нет. */
export const question = { ...base, initialText: 'что именно делает /compact с вложениями?' };

/**
 * Команда набрана в ещё не начатом чате: строка говорит не «уйдёт чату», а почему
 * команда не пройдёт. Причину называет то же правило, по которому откажет
 * отправка (`chatCommandBlock`), — поле не обещает того, чего не будет.
 */
export const commandBlocked = { ...base, chatId: 'new', initialText: '/compact подробнее про миграции' };

/**
 * Слэш первым символом: один список на два реестра — команды чата и триггеры
 * чипов. Разделы и есть то различие, ради которого списки сведены в один:
 * команда уходит чату целиком, триггер лишь дописывается в сообщение.
 */
export const slashMenu = { ...base, initialText: '/' };

/**
 * Тот же список в ещё не начатом чате. `/compact` там не сработает — строка
 * погашена и названа причина, но из списка не убрана: открывают его чаще всего
 * как раз в новом чате.
 */
export const slashMenuBlocked = { ...base, chatId: 'new', initialText: '/' };

/** Набрано `/сж`: ищем по всем синонимам, показываем совпавший — его и вставим. */
export const slashMenuFiltered = { ...base, initialText: '/сж' };

/**
 * Тот же список в узкой колонке: описание пункта длиннее строки и обязано резаться
 * с конца. Путь в списке файлов режется наоборот, с начала, и общий класс на
 * оба отрезал бы фразе как раз то, что называет пункт.
 */
export const slashMenuNarrow = { ...base, initialText: '/' };

/**
 * Чипы из другого репозитория. Проект чата — `kb`, и чип из него подписан одним
 * коротким именем файла; чипы, вставленные до смены проекта, остались за
 * `billing` и называют его в подписи — иначе два одинаковых пути из разных
 * репозиториев в поле ввода неотличимы (chipLabel в fileChips.js).
 *
 * Живьём это состояние стоит второго репозитория и смены проекта в селекторе;
 * здесь оно задаётся черновиком, потому что проект живёт прямо в токене чипа.
 */
export const foreignChips = {
  ...base,
  initialText:
    'сравни ⟦file@billing:backend/pom.xml⟧ с ⟦file@kb:backend/pom.xml⟧ — и что в ⟦commit@billing:9f3c1ab:Поднять Spring Boot до 3.5⟧',
};
