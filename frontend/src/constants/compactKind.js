// Чем вызвано сжатие контекста. Значение приходит с бэка в мете строки-плашки
// (CompactMeta.Kind) и решает две вещи: как плашка выглядит и что после неё
// известно про занятый контекст.
export const COMPACT_KIND = {
  // Команда пользователя `/compact`.
  COMPACT: 'COMPACT',
  // То же полное сжатие, но запущенное самим чатом у предела контекста модели.
  AUTO_COMPACT: 'AUTO_COMPACT',
  // Команда пользователя `/compact-1`: сжато всё, кроме последнего хода разговора, — он остался
  // живым под плашкой.
  COMPACT_KEEP_LAST: 'COMPACT_KEEP_LAST',
  // Фоновая суммаризация: сжато начало истории, живой хвост под плашкой остался.
  SUMMARIZE: 'SUMMARIZE',
};

// Виды, после которых под плашкой остаётся живой хвост. Перечислены именно они, а не полные:
// незнакомый вид обязан читаться как полное сжатие (см. isFullCompaction).
const PARTIAL_KINDS = new Set([COMPACT_KIND.SUMMARIZE, COMPACT_KIND.COMPACT_KEEP_LAST]);

/**
 * Сжатие заменило сводкой ВЕСЬ живой контекст — тогда его размер после плашки можно оценить по
 * сводке. У фоновой суммаризации и у `/compact-1` так не выходит: под плашкой остался живой хвост,
 * и его размер ниоткуда не известен.
 *
 * Вид, которого эта версия не знает, считается полным сжатием — так же, как читает его бэк.
 */
export const isFullCompaction = (compact) => !!compact && !PARTIAL_KINDS.has(compact.kind);
