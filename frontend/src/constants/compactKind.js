// Чем вызвано сжатие контекста. Значение приходит с бэка в мете строки-плашки
// (CompactMeta.Kind) и решает две вещи: как плашка выглядит и что после неё
// известно про занятый контекст.
export const COMPACT_KIND = {
  // Команда пользователя `/compact`.
  COMPACT: 'COMPACT',
  // То же полное сжатие, но запущенное самим чатом у предела контекста модели.
  AUTO_COMPACT: 'AUTO_COMPACT',
  // Фоновая суммаризация: сжато начало истории, живой хвост под плашкой остался.
  SUMMARIZE: 'SUMMARIZE',
};

/**
 * Сжатие заменило сводкой ВЕСЬ живой контекст — тогда его размер после плашки можно оценить по
 * сводке. У фоновой суммаризации так не выходит: под плашкой остался живой хвост, и его размер
 * ниоткуда не известен.
 *
 * Вид, которого эта версия не знает, считается полным сжатием — так же, как читает его бэк.
 */
export const isFullCompaction = (compact) => !!compact && compact.kind !== COMPACT_KIND.SUMMARIZE;
