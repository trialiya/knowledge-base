// Что означает «Повторить» под пузырём с ошибкой. Режим ставится в момент ошибки —
// там, где ещё известно, успел ли вопрос сохраниться на бэке; сам обработчик повтора
// уже ничего не переспрашивает.
//
// Пузырь без режима повтора кнопку не показывает: модель начала отвечать, и переиграть
// её ход молча нельзя — дальше пользователь пишет сам («продолжай»).
export const RETRY_MODE = {
  // Вопрос до бэка не доехал (сбой самого POST /runs) — отправляем его текст заново.
  RESEND: 'resend',
  // Вопрос сохранён, ответа нет ни одного — прогон запускается поверх той же истории,
  // без второго USER-сообщения (POST /runs с retry в теле).
  CONTINUE: 'continue',
};
