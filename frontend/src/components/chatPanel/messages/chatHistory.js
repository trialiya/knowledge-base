/**
 * В чате нет ни одного настоящего сообщения — ни вопроса, ни ответа. Такой чат
 * нечем сжимать, и ленте в нём показывать нечего.
 *
 * Пока `messages` не массив, история просто не доехала, и чат пустым НЕ считается:
 * иначе блок git-фраз мелькал бы на открытии, а `/compact` отклонялся бы в чате,
 * где сжимать на самом деле есть что. Пустой массив — это уже ответ «загружено, и
 * там пусто»: так помечен чат, которому id выдало вложение, а не первый вопрос
 * (см. useChatAttachments).
 */
export const isChatEmpty = (chat) => Array.isArray(chat?.messages) && !chat.messages.some((m) => m && m.sender);
