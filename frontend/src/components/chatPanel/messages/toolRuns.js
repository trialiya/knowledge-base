import { SENDER } from '@/constants/messageSender';

/**
 * Ряд из одних вызовов инструментов: модель звала инструменты, не написав ни слова. Ошибка и
 * плашки событий сюда не попадают — им есть что показать помимо вызовов, и своим рядом они
 * остаются.
 */
const isToolsOnly = (msg) =>
  !!msg &&
  msg.sender === SENDER.AI &&
  !!msg.toolCalls?.length &&
  !(msg.text || '').trim() &&
  !msg.error &&
  !msg.compact &&
  !msg.gitEvent &&
  !msg.fileRevert;

/**
 * Склеивает подряд идущие ряды из одних вызовов в один список плашек.
 *
 * Внутри одного прогона таких рядов не бывает: живой редьюсер открывает новый пузырь только
 * под непустой текст, а при загрузке истории сегмент без текста прилипает к предыдущему
 * (`transformPage`). Два таких ряда подряд — это два прогона без вопроса между ними, то есть
 * повтор оборванного: прогон умер, не написав ни слова, и следующий начал с тех же поисков.
 * Разговор от этого не прерывался, а лента показывала разрыв — с зазором на месте реплики,
 * которой нет, и с группировкой, обрывающейся на границе (тот же инструмент шёл бы «×2», а
 * следом отдельной плашкой).
 *
 * Склейка чисто показная: сами сообщения не трогаются, и `callIndex`, уникальный лишь внутри
 * прогона, ни с чем не сравнивается — плашки группируются по имени, а детали ищутся по
 * `callId`, который уникален в чате.
 *
 * Держится она, пока обоим рядам нечего показать, кроме вызовов: остановка и ошибка дописывают
 * в пузырь свою пометку, и склеенный ряд распадается обратно на два — вместе с открытой на
 * вызове второго прогона модалкой деталей (её состояние лежит в ряду, который эти вызовы
 * показывал). Отдельного лечения это не получило: чтобы такое увидеть, нужны два оборванных
 * прогона подряд и открытые детали ровно в момент, когда обрывается второй.
 *
 * Возвращает массив ровно той же длины, что `messages`, — индексы ленты не сдвигаются, на них
 * завязаны и блоки правок в конце ответа, и поиск откатываемого ответа:
 *
 * - `null` — ряд рисуется как обычно;
 * - `{ absorbed: true }` — вызовы этого ряда уже показаны предыдущим, своего рисовать не нужно;
 * - `{ toolCalls }` — начало склейки: вызовы всех рядов подряд одним списком.
 */
export const toolRunsIn = (messages) => {
  const runs = messages.map(() => null);
  for (let i = 0; i < messages.length; i++) {
    if (!isToolsOnly(messages[i])) continue;
    if (isToolsOnly(messages[i - 1])) {
      runs[i] = { absorbed: true };
      continue;
    }
    let end = i + 1;
    while (end < messages.length && isToolsOnly(messages[end])) end++;
    // Одиночный ряд оставляем как есть: склеивать нечего, а новый массив на каждое обновление
    // ленты обесценил бы memo пузыря. У склеенного ряда он и правда обесценен — но в нём одни
    // плашки, без markdown, и обновления к нему приходят по вызову инструмента, а не по чанку
    // текста: текст прекратил бы склейку, сделав ряд обычным.
    if (end > i + 1) {
      runs[i] = { toolCalls: messages.slice(i, end).flatMap((m) => m.toolCalls) };
    }
  }
  return runs;
};
