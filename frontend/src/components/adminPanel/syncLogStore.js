// ─── Журнал импорта ──────────────────────────────────────────────────────────
// Итог импорта — четыре числа: создано, обновлено, удалено, не удалось. По ним
// не видно ни какие именно узлы записались, ни почему пропущены остальные, а
// именно это и хочется знать после прогона, который что-то поменял в базе.
// Бэк шлёт кадр PROGRESS на каждый тронутый узел с действием и — у отказов —
// причиной; здесь эти кадры превращаются в строки журнала.
//
// Отсюда же ограничение: дерево бывает большим, и держать в состоянии React
// десять тысяч строк не за чем — их всё равно никто не прочитает. Поэтому
// хранится начало журнала, а отказы — всегда: они и есть то, ради чего в
// журнал заглядывают, и потерять их из-за тысячи успешных строк перед ними
// значило бы сделать раздел бесполезным ровно в том случае, когда он нужен.

/** Сколько успешных строк хранится, прежде чем начнёт считаться «и ещё N». */
export const LOG_LIMIT = 200;

export const EMPTY_LOG = { lines: [], dropped: 0 };

/** Отказ — единственное действие, которое не выбрасывается по лимиту. */
export const FAILED = 'failed';

/**
 * Добавляет кадр PROGRESS в журнал.
 *
 * Кадры без action — прогресс экспорта: он делает с каждым узлом одно и то же,
 * и строка «записан» на каждый файл ничего не объясняет. В журнал они не идут.
 *
 * @param {{lines: Array, dropped: number}} log
 * @param {{path: string, action?: string, message?: string}} event
 */
export const appendLine = (log, event) => {
  if (!event?.action) return log;
  if (log.lines.length >= LOG_LIMIT && event.action !== FAILED) {
    return { lines: log.lines, dropped: log.dropped + 1 };
  }
  return {
    lines: [...log.lines, { path: event.path, action: event.action, message: event.message ?? null }],
    dropped: log.dropped,
  };
};

/** Сколько узлов было тронуто всего — включая не попавшие в строки. */
export const logTotal = (log) => log.lines.length + log.dropped;
