/**
 * Какой проект показывать и о каком предупреждать, когда проект пришёл извне —
 * из адреса (панель «Файлы») или из записи чата.
 *
 * Проект мог пережить и выключение репозитория, и переименование id: бэкенд на
 * неизвестный отвечает 400, а чат молча ушёл бы отвечать по другому репозиторию,
 * и выглядело бы это как обычный ответ. Поэтому неизвестный проект заменяется
 * дефолтным, а его id возвращается отдельно — тому, кто умеет об этом сказать.
 *
 * Пустой список — это «списка нет» (ответ ещё не пришёл или запрос отказал), а не
 * «такого проекта нет»: судить по нему нельзя, иначе сбой запроса конфигурации
 * подменял бы репозиторий в совершенно живом адресе.
 *
 * @returns {{ selected: string, missing: string|null }}
 */
export function resolveProjectChoice(project, projectOptions, defaultProjectId) {
  const known = !project || projectOptions.length === 0 || projectOptions.some((o) => o.id === project);
  return {
    selected: (known && project) || defaultProjectId || '',
    missing: known ? null : project,
  };
}
