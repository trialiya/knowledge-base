// Что сейчас открыто поверх страницы: диалоги (ModalShell) и поповеры
// (useDismissable). Нужно двоим сортам потребителей:
//
//  • вложенный диалог не должен уносить Escape'ом родительский — отсюда стопка
//    с понятием «верхняя»;
//  • поверхность под ними (find-бар «Файлов») не должна ловить свои Ctrl+F и
//    Escape, пока поверх неё что-то открыто: этим нажатием закрывают то, что
//    видно, а видно сейчас не её.
//
// Поповеры считаются, а не складываются в стопку: Escape закрывает их все разом,
// и «кто верхний» для них не значит ничего.
//
// Модуль, а не контекст: оверлеи глобальны по своей природе (портал на body, в
// разных ветках дерева), и провайдер вокруг всего приложения добавил бы
// ре-рендер на каждое открытие.

let stack = [];
let nextId = 0;
let popovers = 0;

/** Выдать идентификатор экземпляра модалки. */
export const nextModalId = () => ++nextId;

/** Открылась: встать наверх стопки. Возвращает функцию «закрылась». */
export function pushModal(id) {
  stack.push(id);
  return () => {
    stack = stack.filter((x) => x !== id);
  };
}

/** Верхняя ли эта модалка — ей и достаётся Escape. */
export const isTopmostModal = (id) => stack[stack.length - 1] === id;

/** Открыт ли хоть один диалог: под ним шорткаты страницы молчат. */
export const hasOpenModal = () => stack.length > 0;

/** Открылся поповер. Возвращает функцию «закрылся». */
export function pushPopover() {
  popovers += 1;
  let released = false;
  return () => {
    if (released) return;
    released = true;
    popovers -= 1;
  };
}

/**
 * Открыт ли поверх страницы хоть какой-нибудь оверлей.
 *
 * Читать это надо ДО того, как оверлей успел закрыться от того же нажатия, —
 * то есть в фазе перехвата: свои слушатели оверлеи вешают на всплытие.
 */
export const hasOverlay = () => stack.length > 0 || popovers > 0;
