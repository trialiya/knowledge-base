// Стопка открытых модалок, верхняя — последняя. Нужна двоим: вложенный диалог
// не должен уносить Escape'ом родительский, а поверхности под оверлеем (find-бар
// «Файлов») не должны ловить свои шорткаты, пока поверх них открыт диалог.
//
// Модуль, а не контекст: стопка глобальна по своей природе (модалки живут в
// портале на body, в разных ветках дерева), и провайдер вокруг всего приложения
// добавил бы ре-рендер на каждое открытие.

let stack = [];
let nextId = 0;

/** Выдать идентификатор экземпляра модалки. */
export const nextModalId = () => ++nextId;

/** Открылась: встать наверх стопки. Возвращает функцию «закрылась». */
export function pushModal(id) {
  stack.push(id);
  return () => {
    stack = stack.filter((x) => x !== id);
  };
}

/** Верхняя ли эта модалка — ей и достаётся Escape. */
export const isTopmostModal = (id) => stack[stack.length - 1] === id;

/** Открыт ли хоть один диалог: под ним шорткаты страницы молчат. */
export const hasOpenModal = () => stack.length > 0;
