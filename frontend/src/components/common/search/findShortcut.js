// ─── Клавиши find-бара: кому принадлежит нажатие ────────────────────────────
// Поверхностей с собственным баром несколько (открытый файл, лента чата), и
// разбирают они шорткат одинаково — а ошибиться тут легко: слушатель висит на
// перехвате у окна и видит нажатие раньше всех остальных.

/**
 * Ctrl/Cmd+F — с оглядкой на раскладку: на нелатинской `e.key` даёт символ
 * раскладки («а»), поэтому смотрим ещё и на физическую клавишу.
 */
export const isFindShortcut = (e) =>
  (e.ctrlKey || e.metaKey) && !e.shiftKey && !e.altKey && (e.key === 'f' || e.key === 'F' || e.code === 'KeyF');

/**
 * Escape пришёл в поле ввода — значит, принадлежит полю, а не бару.
 *
 * Слушатель бара стоит на перехвате (иначе оверлей от того же Escape успел бы
 * закрыться и бар уехал бы вместе с ним), но тем самым он отбирает Escape и у
 * тех, кто ждёт его на всплытии и оверлеем не является: отмена инлайн-
 * переименования, закрытие @mention-подсказки в композере. Такие нажатия
 * пропускаем — иначе одно нажатие делало бы два дела разом, и бар закрывался
 * бы, унося запрос из адреса.
 *
 * Поле самого бара — исключение: Escape в нём закрывает именно бар.
 */
export function isTypingTarget(e) {
  const el = e.target;
  if (!el?.closest) return false;
  if (el.closest('[data-find-bar]')) return false;
  return !!el.closest('input, textarea, [contenteditable=""], [contenteditable="true"]');
}
