/**
 * Ревизия так, как её показывают человеку: хеш — первые семь знаков, как пишет
 * git, а ветка, тег или `HEAD~2` — целиком: их имя и есть то, что читают.
 * Хешем считается только строка из hex-знаков длиннее короткой формы —
 * обрезать `cafe` или `release-1` было бы порчей имени.
 */
export default function shortRev(rev) {
  const value = String(rev || '');
  return /^[0-9a-f]{8,64}$/i.test(value) ? value.slice(0, 7) : value;
}
