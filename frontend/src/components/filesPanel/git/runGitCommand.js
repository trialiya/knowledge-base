/**
 * Одно правило запуска git-команды, общее панели «Файлы» и панели чата.
 *
 * Сигнал «репозиторий сдвинулся» поднимается и на успехе, и на отказе.
 * Конфликтующий `stash pop` сначала накладывает stash и только потом отказывает,
 * оставляя на диске настоящие конфликты; обновляясь только на успехе, панель
 * показывала бы состояние, которого больше нет.
 *
 * Отказ не пробрасывается дальше: обе поверхности показывают его сами и
 * по-разному — модалкой с текстом git'а или строкой на вкладке. Вызывающему
 * возвращается `null`, и по нему он отличает отказ от успеха (пустой вывод —
 * обычный исход половины команд, поэтому проверять результат на «пусто» нельзя).
 *
 * @param command    () => Promise — сам запрос
 * @param onSettled  что перечитать, когда всё кончилось, чем бы ни кончилось
 * @param onSuccess  (result) => void
 * @param onFailure  (error) => void
 */
export default function runGitCommand(command, { onSettled, onSuccess, onFailure }) {
  return command().then(
    (result) => {
      onSuccess?.(result);
      onSettled?.();
      return result;
    },
    (error) => {
      onFailure?.(error);
      onSettled?.();
      return null;
    },
  );
}
