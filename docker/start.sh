#!/bin/sh

# Репозитории смонтированы с хоста и принадлежат хостовому пользователю, а контейнер работает
# из-под kb — git отвергает такое рабочее дерево («dubious ownership»). JGit эту проверку не
# делает, но `git grep` идёт subprocess'ом (GitService), поэтому исключение нужно на каждый путь:
# глобов safe.directory не понимает.
#
# Пути берутся из тех же переменных, что видит бэкенд, а не из схемы монтирования: /projects/<id>
# — рекомендация docs/проект/конфигурация.md, а не обязанность, и путь, положенный мимо неё, молча
# остался бы без исключения — открылся бы через JGit и падал на каждом `git grep`.
# Несмонтированный каталог просто пропускается: проект, репозиторий которого не открылся, отвечает
# отказом сам (GitRegistry), сервер при этом работает. Список собирается заново на каждый старт
# (иначе перезапуск контейнера копил бы дубли строк).
git config --global --unset-all safe.directory 2>/dev/null

seen=''
allow_dir() {
    dir=$1
    # Проверяем сам каталог, а не .git внутри: у рабочего дерева (git worktree) .git — файл, и
    # проверка на каталог отсекла бы как раз тот случай, ради которого исключение и нужно.
    [ -n "$dir" ] && [ -d "$dir" ] || return 0
    case ":$seen:" in
        *":$dir:"*) return 0 ;;
    esac
    seen="$seen:$dir"
    git config --global --add safe.directory "$dir"
}

allow_dir "$PROJECT_PATH"
allow_dir "$PROJECT2_PATH"
# Список, заданный переменными целиком (KB_PROJECTS_<n>_PATH) — так включают третий и далее
# проекты. Читаем без пайпа, чтобы seen не терялся в подоболочке.
while IFS= read -r dir; do
    allow_dir "$dir"
done <<EOF
$(env | sed -n 's/^KB_PROJECTS_[0-9]\{1,\}_PATH=//p')
EOF

exec java $JAVA_OPTS -jar app.jar
