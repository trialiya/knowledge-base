#!/bin/sh

# Репозитории смонтированы с хоста и принадлежат хостовому пользователю, а контейнер работает
# из-под kb — git отвергает такое рабочее дерево («dubious ownership»). JGit эту проверку не
# делает, но `git grep` идёт subprocess'ом (GitService), поэтому исключение нужно на каждый путь:
# глобов safe.directory не понимает. Первый проект (PROJECT_PATH) прописан ещё в образе, а пути
# остальных известны только сейчас — отсюда цикл по /projects/<id> (схема монтирования из
# docs/проект/конфигурация.md). Несмонтированный каталог просто пропускается: проект,
# репозиторий которого не открылся, отвечает отказом сам (GitRegistry), сервер при этом работает.
# Список собирается заново на каждый старт (иначе перезапуск контейнера копил бы дубли строк).
git config --global --unset-all safe.directory 2>/dev/null
for dir in /projects/*; do
    if [ -d "$dir/.git" ]; then
        git config --global --add safe.directory "$dir"
    fi
done

exec java $JAVA_OPTS -jar app.jar
