-- Результаты скриптов чата: значение, которое вернул прогон runScript / runSavedScript или
-- команды /script, под коротким id («r3»), чтобы следующий скрипт того же чата прочитал его
-- через kb.result(id), а инструмент saveScriptResult сохранил во вложение — не прогоняя значение
-- через контекст модели. Пишет и читает таблицу только ChatScriptResults.
--
-- value_json — полное значение (JSON.stringify в самой песочнице), не усечённое до
-- kb.script.limits.max-result-chars, как то, что видит модель: ради этого таблица и нужна.
-- Потолок — kb.script.results.max-chars, хвост сверх kb.script.results.keep-per-chat
-- удаляется при записи следующего.
--
-- seq — номер внутри чата, из него id и складывается; уникальность (conversation_id, seq)
-- отвечает за то, что два одновременных прогона не получат один номер (проигравший повторяет).
CREATE TABLE chat_script_result (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id VARCHAR(255) NOT NULL
        REFERENCES chat_topic (conversation_id) ON DELETE CASCADE,
    seq             INTEGER      NOT NULL,
    script          VARCHAR(512),
    project         VARCHAR(255),
    value_json      TEXT         NOT NULL,
    chars           INTEGER      NOT NULL,
    created_at      TIMESTAMP    NOT NULL,
    CONSTRAINT uq_chat_script_result_seq UNIQUE (conversation_id, seq)
);
