package io.github.trialiya.kb.model.chat.entity;

/**
 * Отрезок чата, прожитый на одном репозитории: сообщения с позиции {@code from} по {@code to}
 * включительно относятся к проекту {@code project}. Диапазон закрытый с обеих сторон.
 *
 * <p>Спаны копятся на строке-сводке ({@link ChatMessageMeta#visitedProjects}) и описывают ТОЛЬКО
 * сжатую часть истории: живой хвост считается на чтении ({@code ActiveProjectNotice}) и хранимого
 * значения не переписывает. Поэтому записанный спан не бывает «открытым» и не требует правки, когда
 * чат продолжается.
 *
 * <p>Порядок хронологический, соседние отрезки смыкаются, а один и тот же проект встречается
 * столько раз, сколько чат в него возвращался: A→B→A — это три спана, а не два. Свернув повторы, на
 * вопрос «в каком репозитории читан файл из сообщения 40» ответить было бы уже нечем.
 *
 * <p>Позиции — те же, которыми чат адресуется в промпте ({@code [msg:N]}), и {@code
 * getOriginalMessages} достаёт по ним даже сжатые сообщения ({@code MessageLookupFunction} не
 * фильтрует по {@code summarized}). Диапазон в промпте поэтому не украшение: по нему модель может
 * сходить и прочитать.
 */
public record ProjectSpan(String project, long from, long to) {}
