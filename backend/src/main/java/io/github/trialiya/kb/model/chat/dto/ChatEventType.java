package io.github.trialiya.kb.model.chat.dto;

import io.github.trialiya.kb.model.chat.entity.RunTokenUsage;

/**
 * Тип события в канале чата (см. {@link ChatEvent}). Один поток событий обслуживает и стриминг
 * ответа, и кросс-вкладочную синхронизацию.
 */
public enum ChatEventType {
    /**
     * Сообщение пользователя — эхо для остальных вкладок ({@code payload}: {@link
     * UserMessagePayload}).
     */
    USER_MESSAGE,
    /**
     * Сообщение принято в очередь идущего прогона ({@code payload}: {@link QueuedMessagePayload}) —
     * все вкладки показывают его «ожидающим» пузырём. Доставка в историю приезжает отдельным {@code
     * USER_MESSAGE} (с флагом {@code interjection}, когда она случилась посреди прогона), и до неё
     * сообщение живёт только в {@code chat_pending_message}.
     */
    MESSAGE_QUEUED,
    /** Начало генерации ответа. */
    RUN_STARTED,
    /** Кусок ответа ассистента ({@code payload}: {@link StreamMessage}). */
    STREAM,
    /** Обновление одного вызова инструмента ({@code payload}: {@link ToolCallMessage}). */
    TOOL_CALL,
    /**
     * Итоговый список вызовов инструментов сегмента ({@code payload}: {@link ToolCallsMessage}).
     */
    TOOL_CALLS,
    /**
     * Токены прогона к этому моменту ({@code payload}: {@link RunTokenUsage}) — состояние, а не
     * добавка: событие приходит по нескольку раз за прогон, и каждое следующее заменяет предыдущее
     * целиком. Провайдер без поддержки usage в стриме не присылает его ни разу, и это отличается от
     * нуля — считать нечего, а не насчитали ноль.
     */
    RUN_USAGE,
    /** Генерация успешно завершена. */
    RUN_DONE,
    /** Генерация остановлена пользователем. */
    RUN_STOPPED,
    /** Генерация прервана ошибкой. */
    RUN_ERROR,
    /**
     * Реплей неполон: часть событий этого прогона уже вытеснена из лога хаба (см. {@code
     * ConversationHub}). Приходит перед реплеем и только той вкладке, которой выброшенное
     * предназначалось. Показанный ею ответ с этого момента заведомо с дырой — целиком он будет в
     * истории, когда прогон закончится, оттуда вкладка его и перечитывает.
     */
    REPLAY_GAP,
    /** Чат удалён (в т.ч. из другой вкладки) — открытые на нём вкладки должны закрыть его. */
    CHAT_DELETED,
    /**
     * Началось сжатие контекста по команде {@code /compact}. Отдельная тройка событий, а не RUN_*:
     * прогона здесь нет — нет ни стриминга, ни ответа ассистента, ни остановки, — но чат занят так
     * же, как на генерации, и вкладки обязаны это показать.
     */
    COMPACT_STARTED,
    /** Контекст сжат ({@code payload}: {@link CompactPayload}). */
    COMPACT_DONE,
    /** Сжатие не удалось ({@code payload}: {@code {"message": …}}). */
    COMPACT_ERROR,
    /**
     * В ленте появилась плашка сжатия, которую не просил пользователь ({@code payload}: {@link
     * CompactPayload}): применена отложенная фоновая сводка ({@code PendingSummaryService}) или чат
     * сжал себя сам у предела контекста ({@code AutoCompactService}).
     *
     * <p>Отличие от {@link #COMPACT_DONE} — не в поводе, а в месте: там плашка заменяет пузырь
     * прогона и встаёт в конец ленты, здесь встаёт по своему времени, то есть туда, где кончается
     * свёрнутое. Чат событие не занимает и прогона себе не заводит; {@code runId} у него есть
     * только тогда, когда за раунд заплатил чей-то прогон.
     */
    COMPACT_APPLIED,
    /**
     * Пользователь выполнил git-команду из этого чата ({@code payload}: {@link GitCommandPayload}).
     * Событие, а не только ответ на POST: команда меняет репозиторий для всех вкладок сразу, и та,
     * что её не запускала, обязана показать и новый ряд истории, и сдвинувшуюся ветку.
     */
    GIT_COMMAND,
    /**
     * Пользователь откатил файловые правки ответа ({@code payload}: {@link FileRevertPayload}).
     * Событие по той же причине, что и {@link #GIT_COMMAND}: рабочее дерево изменилось для всех
     * вкладок сразу, и та, что откат не запускала, обязана показать и новый ряд истории, и
     * пропавшие правки.
     */
    FILE_REVERT
}
