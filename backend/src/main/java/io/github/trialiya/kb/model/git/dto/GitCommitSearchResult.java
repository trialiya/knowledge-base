package io.github.trialiya.kb.model.git.dto;

import java.util.List;

/**
 * Поиск коммитов: страница поиска ({@code GET /api/git/commits/grep}) и пикер плейсхолдера
 * ({@code GET /api/git/commits/search}).
 *
 * <p>У {@code git log} нет индекса по сообщениям, и обход истории ограничен, поэтому «ничего не
 * найдено» бывает двух видов: история кончилась — или кончился предел обхода, а дальше по истории
 * совпадения могли быть. Второе и есть {@code truncated}; без него пустая выдача на длинной истории
 * утверждала бы, что искомого нет.
 *
 * @param commits совпавшие коммиты, свежие первыми; описание в {@code body} — только у страницы
 *     поиска, пикеру хватает заголовка
 * @param truncated совпадений может быть больше: за лимитом нашлось ещё одно, или обход
 *     остановился на своём пределе раньше конца истории. Лимит, заполненный последним совпадением
 *     истории, — полная выдача, {@code false}
 */
public record GitCommitSearchResult(List<GitCommit> commits, boolean truncated) {}
