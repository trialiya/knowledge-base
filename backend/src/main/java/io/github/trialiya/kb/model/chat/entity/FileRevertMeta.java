package io.github.trialiya.kb.model.chat.entity;

import java.util.List;
import org.jspecify.annotations.Nullable;

/**
 * Откат файловых правок одного ответа: пользователь посмотрел, что модель написала в рабочее
 * дерево, и вернул файлы к состоянию до ответа (см. {@code ChatFileRevert}).
 *
 * <p>Лежит на ряду, который откат оставил в истории, — как {@link GitEventMeta} у git-команды, и по
 * той же причине: действие происходит между сообщениями, показать его надо сразу, а следующего
 * вопроса может долго не быть. Ряд один и обслуживает обоих читателей: фронт рисует по нему плашку,
 * модель получает собранный при чтении нотис ({@code PromptNotices.fileRevertNotice}), поэтому
 * формулировку для модели можно менять, не переписывая историю.
 *
 * @param project канонический id репозитория, в котором откатили; null — в развёртке проект не
 *     настроен, и вопрос «в каком репозитории» имеет один ответ
 * @param paths пути откаченных файлов в том виде, в каком их пишет репозиторий — то, что видит
 *     пользователь в плашке и что модель обязана перечитать, прежде чем на них опираться
 */
public record FileRevertMeta(@Nullable String project, List<String> paths) {

    public FileRevertMeta {
        paths = List.copyOf(paths == null ? List.of() : paths);
    }
}
