package io.github.trialiya.kb.model.tool;

/**
 * Ответ инструмента, привязанный к конкретному репозиторию.
 *
 * <p>Читающие инструменты умеют работать не только с активным проектом чата (аргумент {@code
 * project}, см. {@code GitFunction}), поэтому ответ обязан называть репозиторий, который на самом
 * деле ответил: по нему модель строит ссылку на файл и понимает, к чему относится путь.
 *
 * <p>Этот интерфейс — та же привязка, но для сервера: {@code RecordingToolCallback} снимает с него
 * id и кладёт в {@code ToolInvocation}, а guard записи ({@code
 * ToolInvocationCollector#hasSeenFile}) сверяет по нему, в том ли репозитории модель видела файл.
 * Инструмент, который о репозиториях не знает вовсе (документы, вложения), интерфейс не реализует —
 * его результат сверять не с чем.
 */
public interface ProjectScoped {

    /** Канонический id репозитория, который ответил. */
    String project();
}
